/// Escape a terminal for use inside a TextMate (Oniguruma) pattern.
fn escape(token: &str) -> String {
    let mut out = String::new();
    for c in token.chars() {
        if "\\^$.|?*+()[]{}/".contains(c) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// `\b(a|b|c)\b` over a sorted word list.
fn word_alternation(words: &[String]) -> String {
    format!(
        "\\b({})\\b",
        words
            .iter()
            .map(String::as_str)
            .collect::<Vec<_>>()
            .join("|")
    )
}

fn generated_banner(what: &str) -> Value {
    json!([
        "GENERATED by `cargo xtask grammar-generate` from vendor/upstream/spec/grammar.ebnf.",
        "DO NOT EDIT. `cargo xtask grammar-drift` regenerates this file and compares bytes,",
        "so a hand edit here fails CI as drift — which is the point (ls05 §2).",
        format!("This file: {what}"),
        "The remedy for a real upstream change is always one commit: bump the pin,",
        "re-vendor, `cargo xtask grammar-generate`, commit together.",
    ])
}

/// The TextMate grammar for `source.wolf`.
fn wolf_grammar(inv: &Inventory) -> Value {
    // Keyword scopes, each filtered by the DERIVED set so a name this table
    // knows but the pin dropped cannot survive here.
    let mut keyword_patterns: Vec<Value> = Vec::new();
    let mut placed: BTreeSet<String> = BTreeSet::new();
    for (scope, names) in KEYWORD_SCOPES {
        let words: Vec<String> = names
            .iter()
            .filter(|n| inv.keywords.contains(**n))
            .map(|n| (*n).to_string())
            .collect();
        for w in &words {
            placed.insert(w.clone());
        }
        if words.is_empty() {
            continue;
        }
        keyword_patterns.push(json!({ "name": scope, "match": word_alternation(&words) }));
    }
    // Anything `reserved_kw` carries that KEYWORD_SCOPES forgot still reaches
    // the user's editor, in the generic scope, and still shows as drift.
    let leftover: Vec<String> = inv.keywords.difference(&placed).cloned().collect();
    if !leftover.is_empty() {
        keyword_patterns.push(json!({
            "name": "keyword.other.wolf",
            "match": word_alternation(&leftover),
        }));
    }

    let operator_alternation = inv
        .operators
        .iter()
        .map(|o| escape(o))
        .collect::<Vec<_>>()
        .join("|");

    let types: Vec<String> = TYPE_NAMES.iter().map(|s| (*s).to_string()).collect();

    json!({
        "information_for_contributors": generated_banner("the TextMate grammar for `.lu` source."),
        "name": "Wolf",
        "scopeName": "source.wolf",
        "patterns": [
            { "include": "#comments" },
            { "include": "#attributes" },
            { "include": "#strings" },
            { "include": "#chars" },
            { "include": "#numbers" },
            { "include": "#keywords" },
            { "include": "#types" },
            { "include": "#operators" }
        ],
        "repository": {
            // Doc comments FIRST: the earliest-listed rule wins, and `//`
            // would otherwise swallow `///` and `//!`.
            "comments": {
                "patterns": [
                    {
                        "name": "comment.line.documentation.wolf",
                        "match": "//[/!].*$"
                    },
                    {
                        "name": "comment.line.double-slash.wolf",
                        "match": "//.*$"
                    }
                ]
            },

            // `#[…]` is a BOUNDED region — and so is `#![…]`, the file-wide
            // inner attribute (`[gram.attr.index]`, s126). Wolf has no
            // preprocessor, so `#` must never swallow the rest of the line —
            // the trap `clients/facsimile/inventory.md` records from the
            // other side.
            "attributes": {
                "name": "meta.attribute.wolf",
                "begin": "#!?\\[",
                "end": "\\]",
                "beginCaptures": { "0": { "name": "punctuation.definition.attribute.wolf" } },
                "endCaptures": { "0": { "name": "punctuation.definition.attribute.wolf" } },
                "patterns": [
                    { "include": "#strings" },
                    { "include": "#numbers" }
                ]
            },

            // Order is the whole content of this rule. `"""` before `"`, or
            // the opening fence lexes as an empty string followed by a string
            // start; raw before generalized, or `r"` is read as a
            // generalized literal with the prefix `r`.
            "strings": {
                "patterns": [
                    { "include": "#block-string" },
                    { "include": "#raw-string" },
                    { "include": "#generalized-string" },
                    { "include": "#quoted-string" }
                ]
            },

            "block-string": {
                "name": "string.quoted.triple.wolf",
                "begin": "\"\"\"",
                "end": "\"\"\"",
                "beginCaptures": { "0": { "name": "punctuation.definition.string.begin.wolf" } },
                "endCaptures": { "0": { "name": "punctuation.definition.string.end.wolf" } },
                "patterns": [ { "include": "#interpolation" } ]
            },

            // `r#"…"#`, with the fence balanced BY COUNT through a
            // backreference to the opening capture. This is the one place
            // TextMate is strictly more expressive than the Vim syntax file
            // ls04 shipped: `clients/nvim/inventory.md` has to enumerate
            // `r"`, `r#"`, `r##"`, `r###"` and gives up past three, because
            // Vim's regex has no counting construct. `\1` counts.
            "raw-string": {
                "name": "string.quoted.other.raw.wolf",
                "begin": "\\br(#*)\"",
                "end": "\"\\1",
                "beginCaptures": { "0": { "name": "punctuation.definition.string.begin.wolf" } },
                "endCaptures": { "0": { "name": "punctuation.definition.string.end.wolf" } },
                "patterns": [ { "include": "#interpolation" } ]
            },

            // `re"…"` — an identifier FUSED to a string. The prefix is part of
            // the literal, so it colours as one thing; `re` alone would read
            // as a variable. Adjacency is required, which is what keeps
            // `extern "C"` (a keyword, a space, a string) out of this rule.
            "generalized-string": {
                "name": "string.quoted.other.generalized.wolf",
                "begin": "\\b([A-Za-z_][A-Za-z0-9_]*)(\")",
                "end": "\"",
                "beginCaptures": {
                    "1": { "name": "support.function.generalized.wolf" },
                    "2": { "name": "punctuation.definition.string.begin.wolf" }
                },
                "endCaptures": { "0": { "name": "punctuation.definition.string.end.wolf" } },
                "patterns": [ { "include": "#interpolation" } ]
            },

            "quoted-string": {
                "name": "string.quoted.double.wolf",
                "begin": "\"",
                "end": "\"",
                "beginCaptures": { "0": { "name": "punctuation.definition.string.begin.wolf" } },
                "endCaptures": { "0": { "name": "punctuation.definition.string.end.wolf" } },
                "patterns": [ { "include": "#interpolation" } ]
            },

            // EVERY string literal is an f-string (D26/X9), which is why this
            // rule is included from all four forms rather than from the plain
            // one. The doubled-brace escapes are matched FIRST, so `{{` never
            // opens an interpolation.
            "interpolation": {
                "patterns": [
                    {
                        "name": "constant.character.escape.wolf",
                        "match": "\\{\\{|\\}\\}"
                    },
                    {
                        "name": "meta.embedded.expression.wolf",
                        "begin": "\\{",
                        "end": "\\}",
                        "beginCaptures": { "0": { "name": "punctuation.section.interpolation.begin.wolf" } },
                        "endCaptures": { "0": { "name": "punctuation.section.interpolation.end.wolf" } },
                        "patterns": [
                            { "include": "#format-spec" },
                            { "include": "#numbers" },
                            { "include": "#keywords" },
                            { "include": "#types" },
                            { "include": "#operators" }
                        ]
                    }
                ]
            },

            // `FORMAT_SPEC ::= ':' …` — the `:>3` in `{words:>3}`.
            "format-spec": {
                "name": "constant.other.format-spec.wolf",
                "match": ":[^{}\"]*(?=\\})"
            },

            // `[gram.lex.char]` (D58, the 83f83bb pin): one scalar or one
            // escape between single quotes — `'a'`, `'\n'`, `'\x41'`,
            // `'\u{1F43A}'`. The match is CLOSED (both quotes in one regex,
            // no begin/end region) because a lone `'` is a stray byte in
            // wolf, not a string opener — a region rule would swallow the
            // rest of the line the way `#` must not (the facsimile trap).
            "chars": {
                "name": "constant.character.wolf",
                "match": "'([^'\\\\\\r\\n]|\\\\[ntr0\\\\'\"]|\\\\x[0-9A-Fa-f]{2}|\\\\u\\{[0-9A-Fa-f]+\\})'",
                "captures": { "0": { "name": "constant.character.wolf" } }
            },

            // Radix forms before decimal, or `0x1f` lexes as `0` followed by
            // an identifier. Float before decimal for the same reason.
            "numbers": {
                "patterns": [
                    { "name": "constant.numeric.hex.wolf", "match": "\\b0x[0-9A-Fa-f][0-9A-Fa-f_]*\\b" },
                    { "name": "constant.numeric.octal.wolf", "match": "\\b0o[0-7][0-7_]*\\b" },
                    { "name": "constant.numeric.binary.wolf", "match": "\\b0b[01][01_]*\\b" },
                    { "name": "constant.numeric.float.wolf", "match": "\\b[0-9][0-9_]*(\\.[0-9][0-9_]*([eE][+-]?[0-9][0-9_]*)?|[eE][+-]?[0-9][0-9_]*)" },
                    { "name": "constant.numeric.decimal.wolf", "match": "\\b[0-9][0-9_]*\\b" }
                ]
            },

            "keywords": { "patterns": keyword_patterns },

            "types": {
                "name": "support.type.wolf",
                "match": word_alternation(&types)
            },

            "operators": {
                "name": "keyword.operator.wolf",
                "match": operator_alternation
            }
        }
    })
}

/// A grammar that is nothing but `source.wolf`.
///
/// The `runtime! syntax/wolf.vim` of this client: sourcing rather than copying
/// is the whole point, so a keyword added to the derived set does not need a
/// second edit here to appear.
fn including_grammar(scope: &str, name: &str, what: &str) -> Value {
    json!({
        "information_for_contributors": generated_banner(what),
        "name": name,
        "scopeName": scope,
        "patterns": [ { "include": "source.wolf" } ]
    })
}

/// `src/pin.ts`, from `vendor/upstream/PIN`.
fn pin_ts(pin: &str) -> String {
    let value = |key: &str| -> String {
        pin.lines()
            .map(|l| l.split('#').next().unwrap_or("").trim())
            .find_map(|l| {
                let (k, v) = l.split_once('=')?;
                (k.trim() == key).then(|| v.trim().trim_matches('"').to_string())
            })
            .unwrap_or_default()
    };
    format!(
        r#"// GENERATED by `cargo xtask grammar-generate` from vendor/upstream/PIN.
// Do not edit; `cargo xtask grammar-drift` fails on a hand edit.
//
// The wolf-lang build this extension was verified against. `Wolf: Show Version`
// compares a user's `wolf --version` against `version` and reports a mismatch
// WITHOUT calling it unsupported: a supported version RANGE is ls07's to
// define, and this repo's only honest fact today is one exact pin.

export const PIN = {{
	commit: '{commit}',
	version: '{version}',
	servesLsp: {serves_lsp},
}} as const;
"#,
        commit = value("commit"),
        version = value("version"),
        serves_lsp = value("serves_lsp"),
    )
}

