//! **The VS Code extension's derived artifacts** (ls05 §2).
//!
//! Four files under `clients/vscode/` are *read off* the pin rather than
//! authored, and `grammar-drift` regenerates all four in memory and
//! byte-compares them against what is committed:
//!
//! 1. `syntaxes/wolf.tmLanguage.json` — the TextMate grammar.
//! 2. `syntaxes/wolfi.tmLanguage.json` — `.wolfi`, which is `source.wolf`.
//! 3. `syntaxes/wolf-pkg.tmLanguage.json` — `wolf.pkg`/`wolf.sum`, likewise.
//! 4. `src/pin.ts` — the `wolf` build the extension was verified against, the
//!    same generated constant `clients/nvim/lua/wolf/pin.lua` is.
//!
//! **Why the check is on generated bytes rather than on a keyword list.** ls04
//! compares `syntax/wolf.vim`'s `syn keyword` lines against `reserved_kw` and
//! lets a human write the file. That works for a `.vim` file a human can read
//! at a glance. A `.tmLanguage.json` is 200 lines of escaped regex, and a
//! hand-edit in the middle of it is invisible to any check that only looks at
//! the terminal lists. Generating the whole document and diffing the bytes
//! makes a hand-edit *be* the drift — which is the property ls05 §2 asks for in
//! those words ("the check is on the *generated* content precisely so that
//! hand-edits are visible as drift").
//!
//! # What is derived, and what is not
//!
//! Derived from `vendor/upstream/spec/grammar.ebnf`:
//!
//! - the **keyword set**, from `reserved_kw` — the same 50 names, read by the
//!   same [`crate::reserved_keywords`] the Neovim check uses, so the two
//!   clients cannot disagree about what a keyword is;
//! - the **operator inventory**, from every quoted terminal in the file that is
//!   neither a keyword nor a delimiter.
//!
//! Hand-written here, because the EBNF cannot supply it: the scope *structure*
//! — comment forms, the four string forms and their ordering, `{}`
//! interpolation as an embedded expression scope, `#[…]` as a bounded region,
//! and the number patterns. This is ls05 §2's split, and [`TYPE_NAMES`] is the
//! one place it leaks (see its own comment).
//!
//! # THE OPERATOR GAP — closed at pin f9ee9aa
//!
//! Through the 70bdd35 pin, `wolf xtask spec-extract` **elided the precedence
//! climb**, so the derived inventory was missing `==` `!=` `<` `>` `<=` `>=`
//! `<=>` `&&` `||` `<<` `>>` `/` `&` — thirteen operators that lived only in
//! the un-vendored `spec/01-grammar.md` §3.2, and therefore did not highlight
//! (`==` rendered as two `=`). ls02/ls04 recorded the gap; the remedy was
//! always upstream, and upstream took it: the f9ee9aa EBNF renders the full
//! climb (tiers 3–13) into the extracted grammar, the thirteen are ordinary
//! quoted terminals now, and
//! `the_precedence_climb_operators_stay_in_the_vendored_ebnf` keeps them from
//! silently vanishing again. History: `clients/vscode/inventory.md`.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use serde_json::{Value, json};

/// Word terminals the EBNF carries that are **not** reserved keywords.
///
/// Each is an ordinary identifier everywhere except one position
/// (`[gram.inv.ctx]`), so none of them is highlighted: painting `from` and
/// `timeout` as keywords would be wrong far more often than right, and `self`
/// — the one that tempts hardest — is a field name, a parameter and a local in
/// three other places.
///
/// `E`, `e` and `_` are here for a different reason: they are fragments of the
/// number and pattern grammars (`EXPONENT`, `closed_pattern`), matched by the
/// hand-written numeric rules rather than as words. `n`, `r` and `t` joined
/// them at the 83f83bb pin: they are the escape letters of `CHAR_ESC`
/// (`[gram.lex.char]`, D58), matched inside the hand-written char-literal
/// rule, and colouring the letter `n` as a keyword would be wrong everywhere
/// outside `'\n'`.
///
/// This list is **exhaustive over the pin**, and generation fails when a word
/// terminal appears in neither it nor `reserved_kw`. That failure is the point:
/// a contextual keyword added upstream (`sync`, say) forces a human decision
/// about whether it is contextual or reserved, instead of silently becoming
/// neither.
const CONTEXTUAL: &[&str] = &[
    "E", "_", "c", "e", "from", "inout", "lateout", "n", "noalias", "out", "pkg", "pool", "r",
    "rc", "self", "t", "timeout",
];

/// Symbolic terminals that are **delimiters or literal-form fragments**, not
/// operators.
///
/// The partition is hand-drawn and this is the whole of it: everything
/// symbolic that is not listed here becomes an operator. So a symbol added
/// upstream highlights immediately (and shows up as drift), which is the right
/// default — an uncoloured new operator is a smaller wrong than a silent one.
const DELIMITERS: &[&str] = &[
    "\"", "#![", "#[", "(", ")", ",", ".", ":", "[", "]", "{", "}", // punctuation
    "{{", "}}", // the f-string brace escapes, matched inside strings
    "0b", "0o", "0x", // integer radix prefixes, matched by the numeric rules
    // char-literal fragments ([gram.lex.char], the 83f83bb pin): the quote,
    // the backslash and the `\x`/`\u{` escape openers, and the bare `0` of
    // `'\0'` — matched inside the hand-written char rule, never operators.
    "'", "0", "\\", "\\u{", "\\x",
];

/// The type names the grammar paints, and the one thing in this file that the
/// drift check does **not** cover.
///
/// Wolf's fixed-width scalar inventory is REAL at this pin: spec/10 (types,
/// D54) writes `f32`/`f64`/`i32`/`u8` normatively, and the compiler's closed
/// `BUILTIN_TYPES` set at 83f83bb is the fifteen scalars, `char` (s121, D58
/// — `[type.char]` made it a builtin at this pin) and the `wrapping`
/// constructor (D56) painted here, with `Self` beside them. (Through the
/// 70bdd35 pin this list was four names, because no `spec/*.md` then named a
/// fixed-width scalar and inventing them would have taught users a language
/// that did not exist.) Still *not* re-derivable from the vendored EBNF,
/// which has no rule listing type names — a type added upstream will not
/// appear here on its own; re-read `wolf_sema/src/prelude.rs` at each pin.
/// `type` and `region` are type-level too, but they are reserved keywords and
/// are already coloured as such.
const TYPE_NAMES: &[&str] = &[
    "Self", "bool", "byte", "char", "f32", "f64", "i16", "i32", "i64", "i8", "int", "str", "u16",
    "u32", "u64", "u8", "uint", "wrapping",
];

/// Which scope each reserved keyword is painted with.
///
/// **The split is cosmetic and the union is the claim** — the same sentence
/// `clients/nvim/inventory.md` makes about its seven `syn keyword` groups.
/// Moving a keyword between scopes changes the colour a theme picks and
/// nothing else; what matters is that every name in `reserved_kw` appears
/// exactly once across all of them, which is a property of the generator
/// rather than of anyone's discipline: the lists below are *filtered* by the
/// derived set, and any keyword this table forgets lands in
/// `keyword.other.wolf` rather than vanishing.
const KEYWORD_SCOPES: &[(&str, &[&str])] = &[
    ("constant.language.wolf", &["false", "true"]),
    ("keyword.control.conditional.wolf", &["else", "if", "match"]),
    (
        "keyword.control.repeat.wolf",
        &["for", "in", "loop", "while"],
    ),
    (
        "keyword.control.flow.wolf",
        &["break", "continue", "defer", "errdefer", "return"],
    ),
    ("keyword.control.import.wolf", &["import", "use"]),
    (
        "keyword.control.concurrency.wolf",
        &[
            "borrow", "freeze", "move", "proc", "region", "scope", "select", "spawn", "when",
        ],
    ),
    (
        "storage.type.wolf",
        &[
            "const", "enum", "fn", "impl", "let", "struct", "trait", "type", "var",
        ],
    ),
    (
        "storage.modifier.wolf",
        &[
            "asm", "assume", "comptime", "copy", "distinct", "dyn", "export", "extern", "handle",
            "mut", "pub", "shared", "take", "unsafe", "weak",
        ],
    ),
    // `as` is a cast and a `use`-rename, and belongs to neither family above.
    // Naming it here rather than letting it fall through to the leftover
    // bucket keeps that bucket meaning exactly one thing: a keyword upstream
    // added that nobody has classified yet.
    ("keyword.other.wolf", &["as"]),
];

/// The terminal inventory, read off the pinned EBNF.
pub struct Inventory {
    /// `reserved_kw`, verbatim.
    pub keywords: BTreeSet<String>,
    /// Operator terminals, **longest first** — a TextMate alternation is
    /// first-match, not longest-match, so `..` listed before `..=` would
    /// colour `..=` as a range followed by a stray `=`.
    pub operators: Vec<String>,
}

/// Every `'…'` terminal in the file, with comments removed first.
///
/// **The comment strip is load-bearing, not tidiness.** `grammar.ebnf` mixes
/// prose comments with quoted terminals, and prose contains apostrophes: line
/// 34 is `/* \`-> !T\` parses via type's '!' type */`. Pairing quotes across
/// that line yields the "terminals" `s ` and ` type */`, and a generator that
/// swallowed those would emit them into a user's editor. Stripping `/* … */`
/// (which may span lines) and the `#` header first leaves a file in which every
/// apostrophe is a terminal delimiter — verified by the fact that the word
/// terminals then partition exactly into `reserved_kw` and [`CONTEXTUAL`].
fn terminals(ebnf: &str) -> BTreeSet<String> {
    let mut stripped = String::with_capacity(ebnf.len());
    let mut rest = ebnf;
    while let Some(open) = rest.find("/*") {
        stripped.push_str(&rest[..open]);
        stripped.push(' ');
        match rest[open..].find("*/") {
            Some(close) => rest = &rest[open + close + 2..],
            None => {
                rest = "";
                break;
            }
        }
    }
    stripped.push_str(rest);

    let mut out = BTreeSet::new();
    for line in stripped.lines() {
        if line.starts_with('#') {
            continue;
        }
        // Line-scoped, so an unbalanced quote can never run away past the end
        // of its own line.
        for token in crate::quoted(line) {
            out.insert(token);
        }
    }
    out
}

/// Derive the inventory, or say exactly what is unclassified.
pub fn inventory(ebnf: &str) -> Result<Inventory, Vec<String>> {
    let mut errors = Vec::new();
    let keywords = crate::reserved_keywords(ebnf);
    if keywords.is_empty() {
        errors.push(
            "no `reserved_kw ::=` rule found in vendor/upstream/spec/grammar.ebnf \
             — the extraction this generator depends on has changed shape"
                .to_string(),
        );
        return Err(errors);
    }

    let mut operators: Vec<String> = Vec::new();
    for term in terminals(ebnf) {
        let word = term.starts_with(|c: char| c.is_alphabetic() || c == '_');
        if word {
            if !keywords.contains(&term) && !CONTEXTUAL.contains(&term.as_str()) {
                errors.push(format!(
                    "the pinned grammar carries the word terminal `{term}`, which is neither in \
                     `reserved_kw` nor in xtask's CONTEXTUAL list. Classify it: a reserved \
                     keyword is coloured, a contextual one is deliberately not \
                     (`[gram.inv.ctx]`). Leaving it unclassified would make it neither."
                ));
            }
        } else if !DELIMITERS.contains(&term.as_str()) {
            operators.push(term);
        }
    }

    // Longest first, then lexicographic — a total order, so the emitted
    // alternation is byte-stable across platforms and runs.
    operators.sort_by(|a, b| b.chars().count().cmp(&a.chars().count()).then(a.cmp(b)));

    if errors.is_empty() {
        Ok(Inventory {
            keywords,
            operators,
        })
    } else {
        Err(errors)
    }
}

