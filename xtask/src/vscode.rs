/// Render a JSON document the way this repo commits JSON: two-space indent
/// (`.editorconfig`) and a trailing newline.
fn render(value: &Value) -> String {
    let mut text = serde_json::to_string_pretty(value).expect("a generated grammar serializes");
    text.push('\n');
    text
}

/// The four generated files, as `(path, contents)`.
fn artifacts(root: &Path) -> Result<Vec<(PathBuf, String)>, Vec<String>> {
    let vendor = root.join("vendor").join("upstream");
    let ebnf_path = vendor.join("spec").join("grammar.ebnf");
    let ebnf = std::fs::read_to_string(&ebnf_path)
        .map_err(|e| vec![format!("{}: {e}", crate::slash(&ebnf_path))])?;
    let pin_path = vendor.join("PIN");
    let pin = std::fs::read_to_string(&pin_path)
        .map_err(|e| vec![format!("{}: {e}", crate::slash(&pin_path))])?;

    let inv = inventory(&ebnf)?;
    let vscode = root.join("clients").join("vscode");
    let syntaxes = vscode.join("syntaxes");

    Ok(vec![
        (
            syntaxes.join("wolf.tmLanguage.json"),
            render(&wolf_grammar(&inv)),
        ),
        (
            syntaxes.join("wolfi.tmLanguage.json"),
            render(&including_grammar(
                "source.wolfi",
                "Wolf interface",
                "`.wolfi` is lexically wolf; this grammar is `source.wolf` and nothing else.",
            )),
        ),
        (
            syntaxes.join("wolf-pkg.tmLanguage.json"),
            render(&including_grammar(
                "source.wolf-pkg",
                "Wolf manifest",
                "`wolf.pkg`/`wolf.sum` are wolf-literal data; this grammar is `source.wolf`.",
            )),
        ),
        (vscode.join("src").join("pin.ts"), pin_ts(&pin)),
    ])
}

/// `grammar-drift` (check) and `grammar-generate` (write).
pub fn derived(root: &Path, write: bool) -> Vec<String> {
    let mut errors = match artifacts(root) {
        Ok(a) => {
            let mut errors = Vec::new();
            for (path, want) in a {
                let have = std::fs::read_to_string(&path).unwrap_or_default();
                if have == want {
                    eprintln!("vscode: {} is current", crate::slash(&path));
                    continue;
                }
                if write {
                    if let Some(parent) = path.parent() {
                        let _ = std::fs::create_dir_all(parent);
                    }
                    match std::fs::write(&path, &want) {
                        Ok(()) => eprintln!("vscode: wrote {}", crate::slash(&path)),
                        Err(e) => errors.push(format!("{}: {e}", crate::slash(&path))),
                    }
                } else {
                    errors.push(format!(
                        "{} differs from what the pin generates — it is GENERATED, so this is \
                         either a hand edit or a stale pin. Remedy, always one commit: \
                         `cargo xtask grammar-generate`, then commit the result with the pin \
                         bump that caused it.",
                        crate::slash(&path)
                    ));
                }
            }
            errors
        }
        Err(e) => e,
    };
    errors.sort();
    errors.dedup();
    errors
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The pinned grammar, so these tests fail on a pin bump that changes the
    /// language rather than passing against a fixture nobody re-vendors.
    fn pinned_ebnf() -> String {
        let path = crate::repo_root()
            .join("vendor")
            .join("upstream")
            .join("spec")
            .join("grammar.ebnf");
        std::fs::read_to_string(path).expect("the vendored grammar is present")
    }

    #[test]
    fn the_pinned_grammar_classifies_every_word_terminal() {
        // The generator refuses to run on an unclassified word, so this is
        // also the assertion that CONTEXTUAL is exhaustive at the pin.
        let inv = inventory(&pinned_ebnf()).expect("every word terminal is classified");
        assert_eq!(
            inv.keywords.len(),
            50,
            "`reserved_kw` is the spec's own checksum; it carries 50 names at this pin"
        );
    }

    /// The exact trap that made the comment strip necessary.
    #[test]
    fn prose_apostrophes_are_not_mistaken_for_terminals() {
        let ebnf = "reserved_kw ::= 'fn'\n\
                    ret_type ::= type /* `-> !T` parses via type's '!' type */\n";
        let found = terminals(ebnf);
        assert!(
            found.contains("fn"),
            "the real terminal survives: {found:?}"
        );
        assert!(
            !found.iter().any(|t| t.contains("type */") || t == "s "),
            "prose leaked into the terminal set: {found:?}"
        );
    }

    #[test]
    fn operators_are_emitted_longest_first() {
        let inv = inventory(&pinned_ebnf()).unwrap();
        let lengths: Vec<usize> = inv.operators.iter().map(|o| o.chars().count()).collect();
        assert!(
            lengths.windows(2).all(|w| w[0] >= w[1]),
            "a first-match alternation must list `..=` before `..`: {:?}",
            inv.operators
        );
    }

    /// The inverse of the tripwire that guarded the ls02/ls04/ls05 extraction
    /// gap: at f9ee9aa the vendored EBNF renders the precedence climb, so the
    /// thirteen operators the old gap was missing are asserted PRESENT — a
    /// pin where they vanish again is a regression upstream, not a shrug.
    #[test]
    fn the_precedence_climb_operators_stay_in_the_vendored_ebnf() {
        let inv = inventory(&pinned_ebnf()).unwrap();
        for op in [
            "==", "!=", "<", ">", "<=", ">=", "<=>", "&&", "||", "<<", ">>", "/", "&",
        ] {
            assert!(
                inv.operators.iter().any(|o| o == op),
                "`{op}` fell OUT of the vendored EBNF — the precedence climb the f9ee9aa \
                 extraction renders (spec [gram.expr.prec]) has regressed. See \
                 `clients/vscode/inventory.md` §THE OPERATOR GAP for the history."
            );
        }
    }

    #[test]
    fn every_reserved_keyword_reaches_the_emitted_grammar_exactly_once() {
        let inv = inventory(&pinned_ebnf()).unwrap();
        let grammar = wolf_grammar(&inv);
        let patterns = grammar["repository"]["keywords"]["patterns"]
            .as_array()
            .expect("keyword patterns");
        let mut seen: Vec<String> = Vec::new();
        for p in patterns {
            let m = p["match"].as_str().expect("a match pattern");
            let inner = m
                .trim_start_matches("\\b(")
                .trim_end_matches(")\\b")
                .to_string();
            seen.extend(inner.split('|').map(str::to_string));
        }
        seen.sort();
        let mut expected: Vec<String> = inv.keywords.iter().cloned().collect();
        expected.sort();
        assert_eq!(
            seen, expected,
            "the union of the keyword scopes must be exactly `reserved_kw` — the split is \
             cosmetic, the union is the claim"
        );
    }

    /// A keyword this table has never heard of must still reach the editor.
    #[test]
    fn an_unmapped_keyword_lands_in_the_generic_scope_rather_than_vanishing() {
        let inv = Inventory {
            keywords: ["fn", "sync"].iter().map(|s| (*s).to_string()).collect(),
            operators: vec!["+".to_string()],
        };
        let grammar = wolf_grammar(&inv);
        let rendered = render(&grammar);
        assert!(
            rendered.contains("keyword.other.wolf"),
            "an unmapped keyword needs a home"
        );
        assert!(rendered.contains("sync"), "…and must appear in it");
    }

    #[test]
    fn generation_is_deterministic() {
        let inv = inventory(&pinned_ebnf()).unwrap();
        assert_eq!(render(&wolf_grammar(&inv)), render(&wolf_grammar(&inv)));
    }
}
